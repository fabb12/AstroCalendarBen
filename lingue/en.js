/* The English dictionary.
 *
 * A data file, like the `dati-*.js` catalogues: loaded as a `<script>` before
 * `i18n.js`, which takes it into memory at start-up. From then on every
 * `t(key)` is a `Map` read — switching language costs no request and no work.
 *
 * Why not `en.json`: this application also opens with a double-click on
 * `index.html`, and from `file://` a `fetch('en.json')` is forbidden by the
 * browser — the language would never arrive. The contents are a flat
 * key→text object all the same, that is JSON with one header line.
 *
 * A missing key here is not a broken interface: the manager falls back to the
 * Italian source text and reports the key once in the console. That is the
 * whole point of keys — an untranslated string is visible and countable,
 * instead of being silently half-translated by a glossary.
 */

